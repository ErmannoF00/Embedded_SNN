"""Export trained float32 weights and normalization into a C++17 header."""
import argparse
from pathlib import Path

import numpy as np
import torch

from .model import (AdaptiveLIF, N_INPUT, N_HIDDEN, N_OUTPUT, STEPS,
                    LEAK, ADAPT_DECAY, ADAPT_GAIN, THRESHOLD, READOUT_LEAK)


def print_array(name, array, output):
    array = np.asarray(array, dtype=np.float32).flatten()
    output.write(f"inline constexpr float {name}[{len(array)}] = {{\n")
    for i in range(0, len(array), 8):
        block = ", ".join(f"{float(v):.9g}f" if "." in f"{float(v):.9g}" or "e" in f"{float(v):.9g}" else f"{float(v):.9g}.0f" for v in array[i:i+8])
        output.write(f"    {block},\n")
    output.write("};\n\n")


def export_model(checkpoint: Path, output: Path):
    data = torch.load(checkpoint, map_location="cpu", weights_only=True)
    model = AdaptiveLIF()
    model.load_state_dict(data["state_dict"])
    model.eval()
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w") as f:
        f.write("// Generated by python -m snn_pipeline.export. Do not edit.\n")
        f.write("#pragma once\n\nnamespace model_weights {\n")
        for name, val in (("INPUTS", N_INPUT), ("HIDDEN", N_HIDDEN),
                          ("OUTPUTS", N_OUTPUT), ("TIMESTEPS", STEPS)):
            f.write(f"inline constexpr int {name} = {val};\n")
        for name, val in (("LEAK", LEAK), ("ADAPT_DECAY", ADAPT_DECAY),
                          ("ADAPT_GAIN", ADAPT_GAIN), ("THRESHOLD", THRESHOLD),
                          ("READOUT_LEAK", READOUT_LEAK)):
            f.write(f"inline constexpr float {name} = {float(val):.9f}f;\n")
        f.write("\n// Dense weight layout: W1[hidden][feature], W2[output][hidden].\n")
        params = dict(model.named_parameters())
        for name, array in (("FEATURE_MEAN", data["mean"]),
                            ("FEATURE_STD", data["std"]),
                            ("W1", params["input_proj.weight"].detach().numpy()),
                            ("B1", params["input_proj.bias"].detach().numpy()),
                            ("W2", params["readout_proj.weight"].detach().numpy()),
                            ("B2", params["readout_proj.bias"].detach().numpy())):
            print_array(name, array, f)
        f.write("} // namespace model_weights\n")
    print(f"Exported {output}")


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--checkpoint", type=Path, default=Path("artifacts/checkpoint.pt"))
    p.add_argument("--output", type=Path, default=Path("deployment/generated/model_weights.hpp"))
    args = p.parse_args()
    export_model(args.checkpoint, args.output)
